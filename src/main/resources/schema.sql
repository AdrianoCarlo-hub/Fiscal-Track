-- ============================================================
-- Schema complet pour Fiscal-Track
-- Execute AVANT data.sql par Spring Boot (spring.sql.init.mode=always)
-- Idempotent : CREATE TABLE IF NOT EXISTS / CREATE INDEX IF NOT EXISTS
-- Les 11 tables du mapping JPA (ddl-auto=validate) sont creees ici,
-- ce qui permet un demarrage sur une base PostgreSQL vierge.
-- ============================================================

-- ------------------------------------------------------------
-- 1. Parametres fiscaux : toutes les constantes fiscales
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS parametres_fiscaux (
    code VARCHAR(50) NOT NULL PRIMARY KEY,
    valeur NUMERIC(20, 4) NOT NULL,
    annee_debut INTEGER NOT NULL,
    annee_fin INTEGER,
    base_legale VARCHAR(100) NOT NULL,
    secteur VARCHAR(100),
    description VARCHAR(255)
);

CREATE INDEX IF NOT EXISTS idx_parametres_fiscaux_base_legale ON parametres_fiscaux(base_legale);
CREATE INDEX IF NOT EXISTS idx_parametres_fiscaux_secteur ON parametres_fiscaux(secteur);
CREATE INDEX IF NOT EXISTS idx_parametres_fiscaux_annee ON parametres_fiscaux(annee_debut, annee_fin);

-- ------------------------------------------------------------
-- 2. Agents fiscaux (personnel de la direction)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS agents_fiscaux (
    id_agent VARCHAR(6) NOT NULL PRIMARY KEY,
    nom_agent VARCHAR(255) NOT NULL,
    prenom_agent VARCHAR(255) NOT NULL,
    email_agent VARCHAR(255) NOT NULL,
    telephone_agent VARCHAR(255),
    mot_de_passe_hash_agent TEXT NOT NULL,
    division VARCHAR(255) NOT NULL,
    role_securite VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_agents_fiscaux_email UNIQUE (email_agent)
);

-- ------------------------------------------------------------
-- 3. Contribuables (assujettis)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS contribuables (
    nif VARCHAR(10) NOT NULL PRIMARY KEY,
    raison_sociale VARCHAR(255) NOT NULL,
    forme_juridique VARCHAR(255),
    nom_dirigeant VARCHAR(255),
    prenom_dirigeant VARCHAR(255),
    cin_dirigeant VARCHAR(255),
    email_contribuable VARCHAR(255),
    telephone_contribuable VARCHAR(255),
    adresse_contribuable VARCHAR(255),
    commune_contribuable VARCHAR(255),
    mot_de_passe_hash_contribuable TEXT NOT NULL,
    regime_imposition VARCHAR(255),
    obligation_comptable VARCHAR(255),
    statut_activite VARCHAR(255) NOT NULL,
    date_immatriculation DATE NOT NULL,
    autorisation_ouverture BOOLEAN,
    option_sante BOOLEAN,
    date_cloture DATE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- ------------------------------------------------------------
-- 4. Jours feries (report des echeances - RC1)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS jours_feries (
    id_jour_ferie BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_ferie DATE NOT NULL,
    description VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_jours_feries_date UNIQUE (date_ferie)
);

-- ------------------------------------------------------------
-- 5. Types d'impots (catalogue + configuration des echeances)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS types_impots (
    code_impot VARCHAR(30) NOT NULL PRIMARY KEY,
    nom_impot VARCHAR(255) NOT NULL,
    periodicite VARCHAR(255) NOT NULL,
    echeance_theorique_jour INTEGER,
    echeance_theorique_mois INTEGER,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- ------------------------------------------------------------
-- 6. Obligations fiscales (echeances a respecter)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS obligations_fiscales (
    id_obligation_fiscale BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nif VARCHAR(10) NOT NULL,
    code_impot VARCHAR(30) NOT NULL,
    id_agent VARCHAR(6),
    id_jour_ferie BIGINT,
    periode_fiscale VARCHAR(255) NOT NULL,
    date_limite_theorique DATE NOT NULL,
    date_limite_reelle DATE NOT NULL,
    statut_declaration VARCHAR(255) NOT NULL,
    date_depot_effectif DATE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_obligations_uniquite UNIQUE (nif, code_impot, periode_fiscale)
);

CREATE INDEX IF NOT EXISTS idx_obligations_nif ON obligations_fiscales(nif);
CREATE INDEX IF NOT EXISTS idx_obligations_statut ON obligations_fiscales(statut_declaration);
CREATE INDEX IF NOT EXISTS idx_obligations_echeance ON obligations_fiscales(date_limite_reelle);

-- ------------------------------------------------------------
-- 7. Declarations (depots des contribuables)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS declarations (
    id_declaration BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_obligation_fiscale BIGINT NOT NULL,
    chiffre_affaires_declare NUMERIC(15, 2) NOT NULL,
    impot_principal_calcule NUMERIC(15, 2) NOT NULL,
    date_soumission TIMESTAMP WITH TIME ZONE NOT NULL,
    statut_validation VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    base_imposable NUMERIC(15, 2),
    taux_applique NUMERIC(5, 4),
    montant_brut NUMERIC(15, 2),
    montant_minimum NUMERIC(15, 2),
    acomptes_deduits NUMERIC(15, 2),
    credit_fiscal NUMERIC(15, 2),
    categorie_activite VARCHAR(50),
    detail_calcul TEXT,
    CONSTRAINT uq_declarations_obligation UNIQUE (id_obligation_fiscale)
);

CREATE INDEX IF NOT EXISTS idx_declarations_statut ON declarations(statut_validation);

-- ------------------------------------------------------------
-- 8. Comptes courants fiscaux (ce qui est du par declaration)
-- montant_total_du et reste_a_recouvrer sont des colonnes
-- gerees par PostgreSQL (mapping @Generated, insertable=false)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS comptes_courants_fiscaux (
    id_compte BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_declaration BIGINT NOT NULL,
    nif VARCHAR(10) NOT NULL,
    date_creation_ligne TIMESTAMP WITH TIME ZONE NOT NULL,
    montant_principal NUMERIC(15, 2) NOT NULL,
    montant_penalites NUMERIC(15, 2) NOT NULL,
    montant_amende NUMERIC(15, 2) NOT NULL DEFAULT 0,
    montant_paye NUMERIC(15, 2) NOT NULL,
    montant_total_du NUMERIC(15, 2) GENERATED ALWAYS AS (COALESCE(montant_principal, 0) + COALESCE(montant_penalites, 0) + COALESCE(montant_amende, 0)) STORED,
    reste_a_recouvrer NUMERIC(15, 2) GENERATED ALWAYS AS (COALESCE(montant_principal, 0) + COALESCE(montant_penalites, 0) + COALESCE(montant_amende, 0) - COALESCE(montant_paye, 0)) STORED,
    statut_recouvrement VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_comptes_declaration UNIQUE (id_declaration)
);

CREATE INDEX IF NOT EXISTS idx_comptes_nif ON comptes_courants_fiscaux(nif);
CREATE INDEX IF NOT EXISTS idx_comptes_statut ON comptes_courants_fiscaux(statut_recouvrement);

-- ------------------------------------------------------------
-- 9. Paiements (versements)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS paiements (
    id_paiement BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_compte BIGINT NOT NULL,
    montant_verse NUMERIC(15, 2) NOT NULL,
    date_paiement TIMESTAMP WITH TIME ZONE NOT NULL,
    mode_paiement VARCHAR(255) NOT NULL,
    reference_transaction VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_paiements_reference UNIQUE (reference_transaction)
);

CREATE INDEX IF NOT EXISTS idx_paiements_compte ON paiements(id_compte);

-- ------------------------------------------------------------
-- 10. Notifications (rappels, avis de retard, relances)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS notifications (
    id_notif BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_obligation_fiscale BIGINT,
    id_compte BIGINT,
    nif VARCHAR(10) NOT NULL,
    id_agent VARCHAR(6),
    type_relance VARCHAR(255) NOT NULL,
    message_contenu TEXT NOT NULL,
    date_envoi_prevue TIMESTAMP WITH TIME ZONE NOT NULL,
    date_envoi_effective TIMESTAMP WITH TIME ZONE,
    canal_envoi VARCHAR(255) NOT NULL,
    statut_envoi VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_notifications_nif ON notifications(nif);
CREATE INDEX IF NOT EXISTS idx_notifications_statut ON notifications(statut_envoi);

-- ------------------------------------------------------------
-- 11. Historique des actions (journal d'audit)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS historique_actions (
    id_historique BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur VARCHAR(100) NOT NULL,
    action VARCHAR(100) NOT NULL,
    details TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_historique_utilisateur ON historique_actions(utilisateur);
CREATE INDEX IF NOT EXISTS idx_historique_action ON historique_actions(action);

-- ------------------------------------------------------------
-- 12. Amendes de defaut de depot (CDI 20.01.52)
-- Une seule amende par obligation (contrainte d'unicite = idempotence).
-- Stockee separement des interets de retard ; incluse dans le total du
-- via comptes_courants_fiscaux.montant_amende a la declaration.
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS amendes_defaut_depot (
    id_amende BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_obligation_fiscale BIGINT NOT NULL,
    nif VARCHAR(10) NOT NULL,
    chiffre_affaires NUMERIC(15, 2),
    montant NUMERIC(15, 2) NOT NULL,
    date_calcul TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_amendes_obligation UNIQUE (id_obligation_fiscale)
);

CREATE INDEX IF NOT EXISTS idx_amendes_nif ON amendes_defaut_depot(nif);

-- ------------------------------------------------------------
-- 13. Historique des penalites / majorations (tracabilite)
-- Une ligne est ecrite a chaque changement de montant calcule pour un
-- compte (date de calcul, mois de retard, taux, base, montant).
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS historique_penalites (
    id_historique_penalite BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_compte BIGINT NOT NULL,
    type_ligne VARCHAR(30) NOT NULL,
    date_calcul TIMESTAMP WITH TIME ZONE NOT NULL,
    mois_retard INTEGER,
    taux NUMERIC(8, 4),
    base NUMERIC(15, 2),
    montant NUMERIC(15, 2) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_hist_penalites_compte ON historique_penalites(id_compte);
